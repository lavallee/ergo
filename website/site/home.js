/* Home page: hydrate the hero record, the four enforcement rules, and the
   coordinates — all from data the build generated by running the real
   validator. Nothing here invents a fact; if the data is missing, the authored
   fallback markup stays exactly as written. */
(function () {
  "use strict";

  var meta = window.__ERGO_META__;
  var walk = window.__ERGO_WALK__;
  var kit = window.ergosite;
  if (!kit) return;

  function step(id) {
    if (!walk || !walk.steps) return null;
    return walk.steps.filter(function (s) { return s.id === id; })[0] || null;
  }

  function firstLines(text, count) {
    var lines = String(text || "").split("\n");
    return lines.length > count ? lines.slice(0, count).join("\n") : lines.join("\n");
  }

  // -- hero: the issue that survived the validator --------------------------
  var heroHost = document.getElementById("hero-record");
  var fixed = step("misuse");
  if (heroHost && fixed) {
    heroHost.textContent = "";
    heroHost.appendChild(kit.record({
      path: fixed.record.path,
      label: "· [issue]",
      text: fixed.record.text,
      caption: "Typed, scoped, and carrying the foreseeable misread — plus the move that "
        + "replaces it. The prose under the block holds the story; the block holds the facts."
    }));
  }

  // -- the four enforcement rules -------------------------------------------
  // Each one is anchored to a real refusal or warning in the walkthrough, so
  // the strip cannot claim an enforcement the validator has stopped doing.
  var RULES = [
    {
      title: "You cannot ship a page that names no trap",
      body: "The scaffold does not validate. publisher, source_urls and pitfall — the one "
        + "sentence most likely to save a cold reader — are required fields, so an empty "
        + "page is an error rather than a page that says nothing.",
      from: "scaffold-fails",
      lines: 6
    },
    {
      title: "Scoped, or refused",
      body: "Every issue names the years, columns, tables or entities it touches, and "
        + "effect comes from a closed vocabulary of four. \"Some years are affected\" is a "
        + "bug report; the validator wants the years.",
      from: "first-issue",
      lines: 6
    },
    {
      title: "Name the misuse, or hear about it",
      body: "An issue typed misleads or context is warned about until it names the "
        + "foreseeable misread. The numbers are faithful to the source and a natural "
        + "reading of them is still wrong — that sentence is the whole value of the entry.",
      from: "ward-issue",
      lines: 6
    },
    {
      title: "The doc and the code cannot drift apart",
      body: "A mitigated issue must name the code that handles it, and the code carries a "
        + "greppable anchor naming the issue back. Rename one half and the check fails "
        + "with a non-zero exit — which is what stops a workaround being cleaned up.",
      from: "rename",
      lines: 6
    }
  ];

  var rulesHost = document.getElementById("rules");
  if (rulesHost && walk) {
    RULES.forEach(function (rule) {
      var source = step(rule.from);
      if (!source) return;
      var cell = kit.el("div", "rule");
      cell.appendChild(kit.el("h3", null, rule.title));
      cell.appendChild(kit.el("p", null, rule.body));
      cell.appendChild(kit.record({
        path: "$ " + source.commands[0].replace(/^python3 tools\/ergo\.py /, "ergo "),
        refused: source.refused,
        text: firstLines(source.stdout, rule.lines),
        caption: source.refused ? "exit " + source.exit_code : null
      }));
      rulesHost.appendChild(cell);
    });
  }

  // -- coordinates ----------------------------------------------------------
  if (meta) {
    document.querySelectorAll('[data-fact="version"]').forEach(function (node) {
      node.textContent = "v" + meta.format_version;
    });
    document.querySelectorAll('[data-fact="format-version"]').forEach(function (node) {
      node.textContent = meta.format_version;
    });
    document.querySelectorAll('[data-fact="spec-status"]').forEach(function (node) {
      node.textContent = "spec " + meta.spec_status.replace(/^draft v[\d.]+\s*·\s*/, "draft · ");
    });

    var facts = [
      ["Dependencies", "0", "stdlib only, Python " + meta.requires_python + "+"],
      ["The tool", meta.tool_lines + " lines", "one file you copy into your repo"],
      ["Passing checks", String(meta.checks), "in the suite at " + meta.revision],
      ["Spec", meta.spec_lines + " lines", meta.spec_sections + " sections, " + meta.spec_status],
      ["Issue types", String(meta.issue_types), "recommended taxonomy, extensible"],
      ["Commands", String((meta.cli || []).length), (meta.cli || []).map(function (c) { return c.name; }).join(" · ")],
      ["Example page", meta.example.issues + " issues", meta.example.practices + " practices, from real NJ DOE data"],
      ["Licence", meta.license, "and the format is nobody's"]
    ];

    var host = document.getElementById("facts");
    if (host) {
      facts.forEach(function (row) {
        var cell = kit.el("div", "fact");
        cell.appendChild(kit.el("dt", null, row[0]));
        var value = kit.el("dd", null, row[1]);
        value.appendChild(kit.el("small", null, row[2]));
        cell.appendChild(value);
        host.appendChild(cell);
      });
    }
  }
})();
